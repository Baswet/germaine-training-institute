"""
Application — Step 2 §28 "Table: applications".

reference_code is a separate, non-sequential public identifier
(Step 2 §24) generated by app/utils/reference_code.py — never the
sequential integer id — so applicants can't enumerate other applicants'
records by guessing numbers.

application_type absorbs both the full scholarship wizard
(apply.html, default 'scholarship') and the lighter aiApplyForm
('programme_inquiry') under one table rather than a second, near-
duplicate one. This unification is an explicit architectural judgment
call, flagged (not silently assumed) in Step 2 §39 Open Question D.

programme_mode_id is nullable and only set for AI Bootcamp applications
(academic applications have no mode to select).

referred_by_earncash_user_id / tuition_confirmed_at (added, additive only,
no existing column touched) support the EarnFastCash -> GTI referral
flow: a nullable link to the EarnCash user who referred this applicant
(set only when a real, valid referral_code was supplied at submission
time), and a real admin-confirmed timestamp for when tuition payment
was verified. Both are nullable and absent for the overwhelming
majority of applications, which never came through a referral link.
See app/models/earncash_application_commission.py for how a commission
is created from these two fields — never before both are set, and
never with an invented amount when no real fee_amount exists.
"""

from datetime import datetime, timezone

from app.extensions import db


class Application(db.Model):
    __tablename__ = "applications"
    __table_args__ = (
        db.CheckConstraint(
            "application_type IN ('scholarship', 'general', 'programme_inquiry')",
            name="ck_applications_application_type",
        ),
        db.CheckConstraint(
            "status IN ('submitted', 'under_review', 'offered', 'enrolled', 'rejected', 'withdrawn')",
            name="ck_applications_status",
        ),
    )

    id = db.Column(db.BigInteger().with_variant(db.Integer, "sqlite"), primary_key=True)
    reference_code = db.Column(db.String(20), nullable=False, unique=True)

    applicant_id = db.Column(db.BigInteger, db.ForeignKey("applicants.id"), nullable=False)
    programme_id = db.Column(db.BigInteger, db.ForeignKey("programmes.id"), nullable=False)
    programme_mode_id = db.Column(db.BigInteger, db.ForeignKey("programme_modes.id"), nullable=True)

    application_type = db.Column(db.String(30), nullable=False, default="scholarship")

    education_level = db.Column(db.String(50), nullable=True)
    kcse_grade = db.Column(db.String(10), nullable=True)
    consent = db.Column(db.Boolean, nullable=False, default=False)

    status = db.Column(db.String(20), nullable=False, default="submitted")
    admin_notes = db.Column(db.Text, nullable=True)  # internal only, never public

    referred_by_earncash_user_id = db.Column(
        db.BigInteger, db.ForeignKey("earncash_users.id", ondelete="SET NULL"), nullable=True
    )
    tuition_confirmed_at = db.Column(db.DateTime(timezone=True), nullable=True)

    submitted_at = db.Column(db.DateTime(timezone=True), nullable=False, default=lambda: datetime.now(timezone.utc))
    updated_at = db.Column(
        db.DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )

    applicant = db.relationship("Applicant", back_populates="applications")
    programme = db.relationship("Programme", back_populates="applications")
    programme_mode = db.relationship("ProgrammeMode", back_populates="applications")
    referred_by_earncash_user = db.relationship("EarnCashUser", foreign_keys=[referred_by_earncash_user_id])

    def __repr__(self):
        return f"<Application id={self.id} reference_code={self.reference_code!r}>"
